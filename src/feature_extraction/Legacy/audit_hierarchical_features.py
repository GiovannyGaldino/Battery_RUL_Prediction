from pathlib import Path
from typing import Dict, Any, List, Optional

import numpy as np
import pandas as pd


PARQUET_ENGINE = "fastparquet"

FEATURE_SETS = {
    "F1": "F1_basic",
    "F2": "F2_protocol_aware",
    "F3": "F3_segment_aware",
}


def safe_float(x):
    try:
        x = float(x)
        if np.isfinite(x):
            return x
        return None
    except Exception:
        return None


def to_jsonable(obj):
    """Convert numpy/pandas objects to JSON serializable types."""
    if isinstance(obj, dict):
        return {str(k): to_jsonable(v) for k, v in obj.items()}

    if isinstance(obj, list):
        return [to_jsonable(v) for v in obj]

    if isinstance(obj, tuple):
        return [to_jsonable(v) for v in obj]

    if isinstance(obj, (np.integer,)):
        return int(obj)

    if isinstance(obj, (np.floating,)):
        if np.isfinite(obj):
            return float(obj)
        return None

    if isinstance(obj, (np.ndarray,)):
        return to_jsonable(obj.tolist())

    if pd.isna(obj):
        return None

    return obj


def read_parquet_safe(path: Path) -> Optional[pd.DataFrame]:
    try:
        return pd.read_parquet(path, engine=PARQUET_ENGINE)
    except Exception as exc:
        print(f"[WARN] Could not read {path}: {exc}")
        return None


def find_input_files(
    processed_root: Path,
    feature_set: str,
    phase: str,
    dataset_filter: Optional[str],
    prefer_merged: bool,
) -> List[Path]:
    feature_name = FEATURE_SETS[feature_set]

    files: List[Path] = []

    if prefer_merged:
        merged_file = processed_root / "features_merged" / f"{feature_name}_{phase}_features.parquet"
        if merged_file.exists():
            files.append(merged_file)
            return files

    parts_root = processed_root / "features" / feature_name / phase

    if not parts_root.exists():
        return []

    part_files = sorted(parts_root.glob("*/*/parts/*.parquet"))

    if dataset_filter:
        key = dataset_filter.lower()
        part_files = [p for p in part_files if key in str(p).lower()]

    return part_files


def load_feature_dataframe(
    processed_root: Path,
    feature_set: str,
    phase: str,
    dataset_filter: Optional[str],
    prefer_merged: bool,
) -> tuple[pd.DataFrame, List[str]]:
    files = find_input_files(
        processed_root=processed_root,
        feature_set=feature_set,
        phase=phase,
        dataset_filter=dataset_filter,
        prefer_merged=prefer_merged,
    )

    if not files:
        return pd.DataFrame(), []

    dfs = []
    used_files = []

    for file in files:
        df = read_parquet_safe(file)
        if df is None:
            continue

        if dataset_filter and "dataset" in df.columns:
            df = df[df["dataset"].astype(str).str.lower().str.contains(dataset_filter.lower(), na=False)]

        if len(df) > 0:
            dfs.append(df)
            used_files.append(str(file))

    if not dfs:
        return pd.DataFrame(), used_files

    return pd.concat(dfs, ignore_index=True), used_files


def summarize_basic(df: pd.DataFrame) -> Dict[str, Any]:
    summary: Dict[str, Any] = {}

    summary["n_rows"] = int(len(df))
    summary["n_columns"] = int(df.shape[1])

    if len(df) == 0:
        return summary

    if "dataset" in df.columns:
        summary["datasets"] = sorted(df["dataset"].astype(str).dropna().unique().tolist())

    if "battery_id" in df.columns:
        summary["n_batteries"] = int(df["battery_id"].astype(str).nunique())
        summary["cycles_by_battery"] = (
            df.groupby("battery_id")
            .size()
            .sort_values(ascending=False)
            .astype(int)
            .to_dict()
        )

    if "phase" in df.columns:
        summary["phases"] = sorted(df["phase"].astype(str).dropna().unique().tolist())

    if "cycle_number" in df.columns:
        summary["cycle_number_min"] = safe_float(df["cycle_number"].min())
        summary["cycle_number_max"] = safe_float(df["cycle_number"].max())

    if "remaining_cycles" in df.columns:
        summary["remaining_cycles_min"] = safe_float(df["remaining_cycles"].min())
        summary["remaining_cycles_max"] = safe_float(df["remaining_cycles"].max())
        summary["remaining_cycles_mean"] = safe_float(df["remaining_cycles"].mean())

    if "soh" in df.columns:
        summary["soh_min"] = safe_float(df["soh"].min())
        summary["soh_max"] = safe_float(df["soh"].max())
        summary["soh_mean"] = safe_float(df["soh"].mean())

    return summary


def summarize_missing(df: pd.DataFrame, top_n: int = 40) -> Dict[str, Any]:
    if len(df) == 0:
        return {}

    missing_rate = df.isna().mean().sort_values(ascending=False)
    missing_count = df.isna().sum().sort_values(ascending=False)

    top_missing = []
    for col in missing_rate.index[:top_n]:
        top_missing.append({
            "column": col,
            "missing_count": int(missing_count[col]),
            "missing_rate": float(missing_rate[col]),
        })

    fully_missing_cols = missing_rate[missing_rate >= 1.0].index.tolist()
    high_missing_cols = missing_rate[(missing_rate >= 0.80) & (missing_rate < 1.0)].index.tolist()

    return {
        "top_missing_columns": top_missing,
        "n_fully_missing_columns": int(len(fully_missing_cols)),
        "fully_missing_columns": fully_missing_cols[:200],
        "n_high_missing_columns_ge_80pct": int(len(high_missing_cols)),
        "high_missing_columns_ge_80pct": high_missing_cols[:200],
    }


def summarize_vq_validity(df: pd.DataFrame) -> Dict[str, Any]:
    out: Dict[str, Any] = {}

    for p in [3, 15, 30]:
        col = f"VQ_global_valid_p{p}"
        if col in df.columns:
            values = pd.to_numeric(df[col], errors="coerce")
            out[col] = {
                "valid_count": int((values == 1).sum()),
                "invalid_count": int((values != 1).sum()),
                "valid_rate": float((values == 1).mean()) if len(values) else None,
            }

    for p in [3, 15, 30]:
        for dist_col in [
            f"VQ_global_dist_initial_p{p}",
            f"VQ_global_dist_prev1_p{p}",
            f"VQ_global_dist_prev5_p{p}",
        ]:
            if dist_col in df.columns:
                values = pd.to_numeric(df[dist_col], errors="coerce")
                out[dist_col] = {
                    "non_nan_count": int(values.notna().sum()),
                    "nan_count": int(values.isna().sum()),
                    "mean": safe_float(values.mean()),
                    "min": safe_float(values.min()),
                    "max": safe_float(values.max()),
                }

    return out


def summarize_protocol_features(df: pd.DataFrame) -> Dict[str, Any]:
    out: Dict[str, Any] = {}

    binary_cols = [
        "has_rest",
        "has_relaxation",
        "has_multiple_rest_segments",
        "has_multiple_active_segments",
        "cv_detected",
        "low_dod_flag",
        "is_partial_cycle",
        "is_standard_cycle",
        "usable_for_global_vq",
        "usable_for_segment_vq",
    ]

    for col in binary_cols:
        if col in df.columns:
            values = pd.to_numeric(df[col], errors="coerce")
            out[col] = {
                "count_1": int((values == 1).sum()),
                "count_0": int((values == 0).sum()),
                "nan_count": int(values.isna().sum()),
                "rate_1": float((values == 1).mean()) if len(values) else None,
            }

    numeric_cols = [
        "rest_segment_count",
        "rest_total_duration_s",
        "rest_fraction_duration",
        "rest_mean_delta_v",
        "rest_max_abs_delta_v",
        "rest_mean_rate_v_per_s",
        "active_segment_count",
        "active_segment_count_detected",
        "active_total_duration_s",
        "active_total_capacity_ah",
        "observed_capacity_fraction",
        "observed_voltage_fraction",
        "estimated_dod",
        "cv_duration_s",
        "cv_capacity_fraction",
        "protocol_complexity_level",
    ]

    for col in numeric_cols:
        if col in df.columns:
            values = pd.to_numeric(df[col], errors="coerce")
            out[col] = {
                "non_nan_count": int(values.notna().sum()),
                "nan_count": int(values.isna().sum()),
                "min": safe_float(values.min()),
                "mean": safe_float(values.mean()),
                "median": safe_float(values.median()),
                "max": safe_float(values.max()),
            }

    return out


def sample_interesting_cycles(df: pd.DataFrame, max_rows: int = 30) -> Dict[str, Any]:
    samples: Dict[str, Any] = {}

    base_cols = [
        "dataset",
        "battery_id",
        "phase",
        "cycle_number",
        "cycle_index",
    ]

    candidate_cols = [
        "has_rest",
        "rest_segment_count",
        "has_multiple_rest_segments",
        "rest_total_duration_s",
        "rest_mean_delta_v",
        "rest_max_abs_delta_v",
        "rest1_delta_v",
        "rest1_duration_s",
        "rest2_delta_v",
        "rest2_duration_s",
        "rest3_delta_v",
        "rest3_duration_s",
        "rest4_delta_v",
        "rest4_duration_s",
        "active_segment_count",
        "active_segment_count_detected",
        "has_multiple_active_segments",
        "seg1_available",
        "seg2_available",
        "seg3_available",
        "seg4_available",
        "seg5_available",
        "cv_detected",
        "cv_duration_s",
        "cv_capacity_fraction",
        "low_dod_flag",
        "estimated_dod",
    ]

    cols = [c for c in base_cols + candidate_cols if c in df.columns]

    if not cols:
        return samples

    if "rest_segment_count" in df.columns:
        rest_df = df[pd.to_numeric(df["rest_segment_count"], errors="coerce").fillna(0) > 0]
        samples["cycles_with_rest"] = rest_df[cols].head(max_rows).to_dict(orient="records")

    if "has_multiple_rest_segments" in df.columns:
        multi_rest_df = df[pd.to_numeric(df["has_multiple_rest_segments"], errors="coerce").fillna(0) == 1]
        samples["cycles_with_multiple_rest_segments"] = multi_rest_df[cols].head(max_rows).to_dict(orient="records")

    active_col = None
    if "active_segment_count" in df.columns:
        active_col = "active_segment_count"
    elif "active_segment_count_detected" in df.columns:
        active_col = "active_segment_count_detected"

    if active_col:
        multi_active_df = df[pd.to_numeric(df[active_col], errors="coerce").fillna(0) > 1]
        samples["cycles_with_multiple_active_segments"] = multi_active_df[cols].head(max_rows).to_dict(orient="records")

    if "cv_detected" in df.columns:
        cv_df = df[pd.to_numeric(df["cv_detected"], errors="coerce").fillna(0) == 1]
        samples["cycles_with_cv"] = cv_df[cols].head(max_rows).to_dict(orient="records")

    if "low_dod_flag" in df.columns:
        low_dod_df = df[pd.to_numeric(df["low_dod_flag"], errors="coerce").fillna(0) == 1]
        samples["cycles_low_dod"] = low_dod_df[cols].head(max_rows).to_dict(orient="records")

    return samples


def feature_group_counts(df: pd.DataFrame) -> Dict[str, int]:
    groups = {
        "metadata_target_cols": 0,
        "global_stats_cols": 0,
        "global_vq_cols": 0,
        "global_distance_cols": 0,
        "protocol_cols": 0,
        "rest_cols": 0,
        "cv_cols": 0,
        "segment_cols": 0,
        "other_cols": 0,
    }

    metadata_prefixes = {
        "dataset", "source_file", "source_path", "battery_id", "battery_index",
        "cell_id_original", "cycle_index", "cycle_number", "source_cycle_id",
        "cycle_pair_id", "phase", "cycle_life", "remaining_cycles",
        "remaining_cycles_norm", "eol_criterion", "eol_capacity_ah",
        "initial_capacity_ah", "nominal_capacity_ah", "soh"
    }

    for col in df.columns:
        if col in metadata_prefixes:
            groups["metadata_target_cols"] += 1
        elif col.startswith("VQ_global_p") or col.startswith("VQ_global_area") or col.startswith("VQ_global_slope") or col.startswith("VQ_global_inflection") or col.startswith("VQ_global_valid"):
            groups["global_vq_cols"] += 1
        elif col.startswith("VQ_global_dist"):
            groups["global_distance_cols"] += 1
        elif col.startswith("rest"):
            groups["rest_cols"] += 1
        elif col.startswith("cv_"):
            groups["cv_cols"] += 1
        elif col.startswith("seg") or col.startswith("active_"):
            groups["segment_cols"] += 1
        elif col in {
            "chemistry", "form_factor", "manufacturer", "nominal_voltage_v",
            "ambient_temperature_c", "charge_protocol", "discharge_protocol",
            "c_rate_charge", "c_rate_discharge", "dod", "has_rest",
            "has_relaxation", "has_multiple_rest_segments",
            "has_multiple_active_segments", "protocol_complexity_level",
            "is_standard_cycle", "is_partial_cycle", "low_dod_flag",
            "observed_capacity_window_ah", "observed_capacity_fraction",
            "observed_voltage_window_v", "observed_voltage_fraction",
            "estimated_dod"
        }:
            groups["protocol_cols"] += 1
        elif any(col.startswith(prefix) for prefix in [
            "voltage_", "current_", "temperature_", "power_", "energy_",
            "capacity_", "phase_capacity", "phase_energy", "duration",
            "sample_period", "n_points", "valid_cycle", "usable_"
        ]):
            groups["global_stats_cols"] += 1
        else:
            groups["other_cols"] += 1

    return groups


def audit_feature_set(
    processed_root: Path,
    phase: str,
    feature_set: str,
    dataset_filter: Optional[str],
    prefer_merged: bool,
    top_missing: int,
    sample_rows: int,
) -> Dict[str, Any]:
    df, used_files = load_feature_dataframe(
        processed_root=processed_root,
        feature_set=feature_set,
        phase=phase,
        dataset_filter=dataset_filter,
        prefer_merged=prefer_merged,
    )

    report: Dict[str, Any] = {
        "feature_set": feature_set,
        "feature_set_name": FEATURE_SETS[feature_set],
        "phase": phase,
        "dataset_filter": dataset_filter,
        "used_files": used_files,
        "n_used_files": len(used_files),
    }

    if len(df) == 0:
        report["status"] = "empty_or_not_found"
        return report

    report["status"] = "ok"
    report["basic_summary"] = summarize_basic(df)
    report["feature_group_counts"] = feature_group_counts(df)
    report["missing_summary"] = summarize_missing(df, top_n=top_missing)
    report["vq_validity"] = summarize_vq_validity(df)
    report["protocol_summary"] = summarize_protocol_features(df)
    report["sample_cycles"] = sample_interesting_cycles(df, max_rows=sample_rows)

    return report


def save_report(report: Dict[str, Any], output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with output_path.open("w", encoding="utf-8") as f:
        json.dump(to_jsonable(report), f, ensure_ascii=False, indent=2)


def save_flat_summary(report: Dict[str, Any], output_csv: Path) -> None:
    rows = []

    for fs_report in report.get("feature_set_reports", []):
        basic = fs_report.get("basic_summary", {})
        protocol = fs_report.get("protocol_summary", {})
        vq = fs_report.get("vq_validity", {})

        row = {
            "feature_set": fs_report.get("feature_set"),
            "feature_set_name": fs_report.get("feature_set_name"),
            "phase": fs_report.get("phase"),
            "status": fs_report.get("status"),
            "n_used_files": fs_report.get("n_used_files"),
            "n_rows": basic.get("n_rows"),
            "n_columns": basic.get("n_columns"),
            "n_batteries": basic.get("n_batteries"),
        }

        for p in [3, 15, 30]:
            key = f"VQ_global_valid_p{p}"
            if key in vq:
                row[f"{key}_valid_count"] = vq[key].get("valid_count")
                row[f"{key}_valid_rate"] = vq[key].get("valid_rate")

        for col in [
            "has_rest",
            "has_multiple_rest_segments",
            "has_multiple_active_segments",
            "cv_detected",
            "low_dod_flag",
            "is_partial_cycle",
        ]:
            if col in protocol:
                row[f"{col}_count_1"] = protocol[col].get("count_1")
                row[f"{col}_rate_1"] = protocol[col].get("rate_1")

        for col in [
            "rest_segment_count",
            "rest_total_duration_s",
            "active_segment_count",
            "active_segment_count_detected",
            "protocol_complexity_level",
            "estimated_dod",
        ]:
            if col in protocol:
                row[f"{col}_mean"] = protocol[col].get("mean")
                row[f"{col}_max"] = protocol[col].get("max")

        rows.append(row)

    output_csv.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(output_csv, index=False, encoding="utf-8-sig")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Audit hierarchical feature extraction outputs."
    )

    parser.add_argument(
        "--processed-root",
        type=str,
        default=r"D:\USUÁRIOS\Marcellus\OneDrive\Doutorado\BATERIAS - Ressubmissão\Batteries\data\processed",
        help="Root folder containing features, features_merged, and reports.",
    )

    parser.add_argument(
        "--phase",
        type=str,
        default="charge",
        choices=["charge", "discharge"],
        help="Phase to audit.",
    )

    parser.add_argument(
        "--feature-set",
        type=str,
        default="all",
        choices=["all", "F1", "F2", "F3", "f1", "f2", "f3"],
        help="Feature set to audit.",
    )

    parser.add_argument(
        "--dataset-filter",
        type=str,
        default="matr",
        help="Dataset filter, e.g. matr, calce, hust. Use empty string for all.",
    )

    parser.add_argument(
        "--prefer-merged",
        action="store_true",
        help="Prefer merged parquet files from data/processed/features_merged.",
    )

    parser.add_argument(
        "--top-missing",
        type=int,
        default=50,
        help="Number of top missing columns to report.",
    )

    parser.add_argument(
        "--sample-rows",
        type=int,
        default=30,
        help="Number of interesting sample rows to save in JSON.",
    )

    return parser.parse_args()


def main() -> None:
    args = parse_args()

    processed_root = Path(args.processed_root)

    dataset_filter = args.dataset_filter
    if dataset_filter is not None and dataset_filter.strip() == "":
        dataset_filter = None

    if args.feature_set.lower() == "all":
        feature_sets = ["F1", "F2", "F3"]
    else:
        feature_sets = [args.feature_set.upper()]

    full_report: Dict[str, Any] = {
        "processed_root": str(processed_root),
        "phase": args.phase,
        "dataset_filter": dataset_filter,
        "prefer_merged": bool(args.prefer_merged),
        "feature_sets": feature_sets,
        "feature_set_reports": [],
    }

    for feature_set in feature_sets:
        print(f"Auditing {feature_set} | phase={args.phase} | dataset_filter={dataset_filter}")

        fs_report = audit_feature_set(
            processed_root=processed_root,
            phase=args.phase,
            feature_set=feature_set,
            dataset_filter=dataset_filter,
            prefer_merged=args.prefer_merged,
            top_missing=args.top_missing,
            sample_rows=args.sample_rows,
        )

        full_report["feature_set_reports"].append(fs_report)

        status = fs_report.get("status")
        n_rows = fs_report.get("basic_summary", {}).get("n_rows")
        n_cols = fs_report.get("basic_summary", {}).get("n_columns")
        print(f"  status={status}, rows={n_rows}, cols={n_cols}")

    report_dir = processed_root / "reports" / "feature_extraction"

    suffix = f"{args.phase}"
    if dataset_filter:
        suffix += f"_{dataset_filter.lower()}"

    json_path = report_dir / f"hierarchical_feature_audit_{suffix}.json"
    csv_path = report_dir / f"hierarchical_feature_audit_summary_{suffix}.csv"

    save_report(full_report, json_path)
    save_flat_summary(full_report, csv_path)

    print(f"\nAudit JSON saved to:\n{json_path}")
    print(f"\nAudit CSV saved to:\n{csv_path}")


if __name__ == "__main__":
    main()