"""
Audit hierarchical feature extraction outputs.

This script audits the outputs generated by build_hierarchical_features.py.

It checks:
- merged files and/or part files;
- row counts;
- number of features;
- datasets and batteries present;
- missing values;
- V(Q) interpolation validity;
- rest/relaxation detection;
- CV detection;
- active segment detection;
- low-DoD flags;
- examples of cycles with rest and multiple active segments.

Recommended location:
src/feature_extraction/audit_hierarchical_features.py
"""

from __future__ import annotations

import argparse
import json
