"""
RWTH Aachen / ISEA battery dataset adapter - audit stage.

This script audits the clean charge/discharge files generated by clean_rwth_cycles.py.
It validates the official schema, summarizes cycle quality, writes anomaly tables,
and generates Q(V) and V(Q) plots for visual inspection.

Run
---
python src/adapters/rwth/audit_rwth_cycles.py
"""

from __future__ import annotations

import argparse
import ast
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from tqdm.auto import tqdm

DATASET = "RWTH"
AUDIT_VERSION = "rwth_audit_v1.0"

DEFAULT_BASE_DIR = Path.cwd()
DEFAULT_CLEAN_DIR = DEFAULT_BASE_DIR / "data" / "interim" / "rwth" / "clean"
DEFAULT_REPORT_DIR = DEFAULT_BASE_DIR / "data" / "reports" / "rwth"

